import os
import requests
import sqlite3
from datetime import datetime, timedelta
from dotenv import load_dotenv

load_dotenv()

ACCESS_TOKEN = os.getenv("META_ACCESS_TOKEN")
PHONE_NUMBER_ID = os.getenv("META_PHONE_NUMBER_ID")
DB_FILE = "test_study.db"

HOURS_OF_SILENCE_REQUIRED = 6
NUDGE_TEMPLATE_NAME = "hello_world"


def send_dynamic_nudges():
    print(
        f"[*] Checking database for participants silent for >= {HOURS_OF_SILENCE_REQUIRED} hours..."
    )

    conn = sqlite3.connect(DB_FILE)
    c = conn.cursor()

    # Query: Get active users, their registration time, and their latest logged meal time
    c.execute(
        """
        SELECT 
            u.phone_number, 
            u.start_timestamp, 
            MAX(m.timestamp) as last_meal_time
        FROM users u
        LEFT JOIN test_meal_logs m ON u.phone_number = m.phone_number
        WHERE u.status = 'active'
        GROUP BY u.phone_number
    """
    )

    users_data = c.fetchall()
    conn.close()

    if not users_data:
        print("[-] No active users found in the database.")
        return

    now = datetime.now()
    silence_threshold = timedelta(hours=HOURS_OF_SILENCE_REQUIRED)


endpoint = f"https://graph.facebook.com/v20.0/{PHONE_NUMBER_ID}/messages"
headers = {
    "Authorization": f"Bearer {ACCESS_TOKEN}",
    "Content-Type": "application/json",
}

for phone_number, start_ts, last_meal_time_str in users_data:
    # STEP 1: Determine the user's last known activity time
    if last_meal_time_str:
        # Parse the timestamp generated by datetime.now() in main.py
        try:
            last_activity = datetime.fromisoformat(last_meal_time_str)
        except ValueError:
            # Fallback parser if fromisoformat fails on older Python versions
            clean_time_str = last_meal_time_str.split(".")[0]
            last_activity = datetime.strptime(clean_time_str, "%Y-%m-%d %H:%M:%S")
    else:
        # Fallback: If they haven't logged ANY meals yet, calculate silence from their registration time
        last_activity = datetime.fromtimestamp(start_ts)

    # STEP 2: Calculate silence duration
    time_since_last_activity = now - last_activity

    # STEP 3: Execute condition
    if time_since_last_activity >= silence_threshold:
        print(
            f"[+] TRIGGER: Nudging {phone_number}... (Silent for {time_since_last_activity})"
        )

        payload = {
            "messaging_product": "whatsapp",
            "to": phone_number,
            "type": "template",
            "template": {"name": NUDGE_TEMPLATE_NAME, "language": {"code": "en"}},
        }

        try:
            res = requests.post(endpoint, headers=headers, json=payload)
            if res.status_code == 200:
                print(f"    -> Success")
            else:
                print(f"    -> API Error: {res.text}")
        except Exception as e:
            print(f"    -> Exception: {e}")
    else:
        # Do nothing, they are active
        print(
            f"[-] SKIP: {phone_number} is active. Last logged {time_since_last_activity} ago."
        )

if __name__ == "__main__":
    send_dynamic_nudges()
